// Generate screenshot HTML files for light theme
function generateScreenshotFiles() {
  console.log('📸 Generating light theme screenshot HTML files...');
  console.log('');

  PLATFORMS.forEach(platform => {
    // Generate light theme HTML only
    const lightHTML = createScreenshotHTML(platform, 'light');
    const lightFile = path.join(OUTPUT_DIR, `${platform.id}-light.html`);
    fs.writeFileSync(lightFile, lightHTML);
    console.log(`✅ Created: ${platform.id}-light.html`);
  });

  console.log('');
  console.log(`📁 Light theme screenshot files created in: ${OUTPUT_DIR}`);
}

