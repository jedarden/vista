// Generate screenshot HTML files
function generateScreenshotFiles() {
  console.log('📸 Generating screenshot HTML files...');
  console.log('');

  PLATFORMS_TO_TEST.forEach(platform => {
    const platformData = extractPlatformData(platform.id);
    if (!platformData) {
      console.log(`⚠️  Platform ${platform.id} not found in platform-frames.js`);
      return;
    }

    // Generate light theme HTML
    const lightHTML = createScreenshotHTML(platformData, 'light');
    const lightFile = path.join(OUTPUT_DIR, `${platform.id}-light.html`);
    fs.writeFileSync(lightFile, lightHTML);
    console.log(`✅ Created: ${platform.id}-light.html`);

    // Generate dark theme HTML
    const darkHTML = createScreenshotHTML(platformData, 'dark');
    const darkFile = path.join(OUTPUT_DIR, `${platform.id}-dark.html`);
    fs.writeFileSync(darkFile, darkHTML);
    console.log(`✅ Created: ${platform.id}-dark.html`);
  });

  console.log('');
  console.log(`📁 Screenshot HTML files created in: ${OUTPUT_DIR}`);
}

