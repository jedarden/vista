#!/usr/bin/env node

/**
 * Fix platform screenshot HTML files to include platform frames module
 */

const fs = require('fs');
const path = require('path');

// Platforms to fix
const PLATFORMS = [
  { id: 'twitter', name: 'X (Twitter)', category: 'Social' },
  { id: 'facebook', name: 'Facebook', category: 'Social' },
  { id: 'youtube', name: 'YouTube', category: 'Video' },
  { id: 'slack', name: 'Slack', category: 'Messaging' },
  { id: 'github', name: 'GitHub', category: 'Developer' },
  { id: 'gmail', name: 'Gmail', category: 'Email' },
  { id: 'reddit', name: 'Reddit', category: 'Discussion' }
];

const THEMES = ['light', 'dark'];

const outputDir = path.join(__dirname);

// Generate HTML for a platform and theme
function createPlatformHTML(platform, theme) {
  const themeClass = theme === 'dark' ? 'dark-theme' : 'light-theme';

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${platform.name} - ${theme.charAt(0).toUpperCase() + theme.slice(1)} Theme</title>
  <style>
    * {
      margin: 0;
      padding: 0;
      box-sizing: border-box;
    }

    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Oxygen, Ubuntu, sans-serif;
      background: ${theme === 'dark' ? '#1a1a1a' : '#f5f5f5'};
      padding: 20px;
      display: flex;
      flex-direction: column;
      align-items: center;
      min-height: 100vh;
    }

    .screenshot-header {
      text-align: center;
      margin-bottom: 20px;
      color: ${theme === 'dark' ? '#e0e0e0' : '#333'};
    }

    .screenshot-header h1 {
      font-size: 24px;
      margin-bottom: 8px;
    }

    .screenshot-header p {
      font-size: 14px;
      opacity: 0.7;
    }

    .platform-frame-container {
      width: 100%;
      max-width: 600px;
      background: ${theme === 'dark' ? '#2a2a2a' : '#ffffff'};
      border-radius: 8px;
      overflow: hidden;
      box-shadow: 0 4px 20px rgba(0, 0, 0, 0.3);
    }

    .screenshot-footer {
      margin-top: 20px;
      text-align: center;
      color: ${theme === 'dark' ? '#888' : '#666'};
      font-size: 12px;
    }
  </style>
</head>
<body class="${themeClass}">
  <div class="screenshot-header">
    <h1>${platform.name} Platform Frame</h1>
    <p>Theme: ${theme.charAt(0).toUpperCase() + theme.slice(1)} | Category: ${platform.category}</p>
  </div>

  <div class="platform-frame-container" id="frame-container">
    <!-- Frame will be rendered here -->
  </div>

  <div class="screenshot-footer">
    Generated by Vista Platform Frame Testing (Bead bf-3em63)
  </div>

  <script src="../src/public/platform-frames.js"></script>
  <script src="../src/public/app.js"></script>
  <script>
    // Sample content
    const sampleContent = {
      meta: {
        og: {
          title: 'Comprehensive Platform Frame Testing',
          description: 'This is a detailed description used to test how different platform frames handle content rendering.',
          image: 'https://picsum.photos/800/600',
          site_name: 'VistaTest'
        },
        title: 'Comprehensive Platform Frame Testing',
        description: 'This is a detailed description used to test how different platform frames handle content rendering.',
        themeColor: '#5865f2'
      },
      imageProbe: {
        dominantColor: '#667eea'
      },
      baseUrl: 'https://example.com/test-article'
    };

    // Render the platform frame
    const platformId = '${platform.id}';
    const theme = '${theme}';
    const container = document.getElementById('frame-container');

    try {
      const html = renderPlatformWithContext(
        platformId,
        sampleContent.meta,
        sampleContent.imageProbe,
        sampleContent.baseUrl,
        theme,
        sampleContent.imageProbe.dominantColor
      );
      container.innerHTML = html;
      console.log('Frame rendered successfully');
    } catch (error) {
      container.innerHTML = '<div style="padding: 20px; color: red;">Error rendering frame: ' + error.message + '</div>';
      console.error('Frame rendering error:', error);
    }
  </script>
</body>
</html>`;
}

// Generate all HTML files
console.log('🔧 Fixing platform screenshot HTML files...\n');

let updatedCount = 0;

PLATFORMS.forEach(platform => {
  THEMES.forEach(theme => {
    const filename = `${platform.id}-${theme}.html`;
    const filepath = path.join(outputDir, filename);

    const html = createPlatformHTML(platform, theme);
    fs.writeFileSync(filepath, html);

    console.log(`✅ Updated: ${filename}`);
    updatedCount++;
  });
});

console.log(`\n✨ Updated ${updatedCount} HTML files successfully!`);
console.log('\n📋 Next steps:');
console.log('1. Open index.html in a browser to test each platform');
console.log('2. Use ADB to capture screenshots of each platform in both themes');
console.log('3. Verify visual appearance and frame rendering');