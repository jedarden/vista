#!/usr/bin/env node

/**
 * Dark Theme Platform Screenshot HTML Generator (Bead bf-b6pnm)
 *
 * This script generates HTML files for capturing dark theme platform screenshots.
 *
 * Usage: node screenshots/dark-theme/generate-dark-theme-html.js
 */

const fs = require('fs');
const path = require('path');

// Platforms to generate dark theme screenshots for
const PLATFORMS = [
  { id: 'twitter', name: 'X (Twitter)', category: 'Social' },
  { id: 'discord', name: 'Discord', category: 'Messaging' },
  { id: 'instagram', name: 'Instagram', category: 'Social' },
  { id: 'telegram', name: 'Telegram', category: 'Messaging' },
  { id: 'signal', name: 'Signal', category: 'Messaging' },
  { id: 'whatsapp', name: 'WhatsApp', category: 'Messaging' },
  { id: 'mastodon', name: 'Mastodon', category: 'Social' }
];

const THEME = 'dark';
const OUTPUT_DIR = __dirname;

console.log('🌙 Dark Theme Platform Screenshot HTML Generator (Bead bf-b6pnm)');
console.log('='.repeat(60));

// Create HTML template for each platform
function createPlatformHTML(platform) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${platform.name} - Dark Theme</title>
  <style>
    * {
      margin: 0;
      padding: 0;
      box-sizing: border-box;
    }

    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Oxygen, Ubuntu, sans-serif;
      background: #1a1a1a;
      padding: 20px;
      display: flex;
      flex-direction: column;
      align-items: center;
      min-height: 100vh;
    }

    .screenshot-header {
      text-align: center;
      margin-bottom: 20px;
      color: #e0e0e0;
    }

    .screenshot-header h1 {
      font-size: 24px;
      margin-bottom: 8px;
    }

    .screenshot-header p {
      font-size: 14px;
      opacity: 0.7;
    }

    .platform-frame-container {
      width: 100%;
      max-width: 600px;
      background: #2a2a2a;
      border-radius: 8px;
      overflow: hidden;
      box-shadow: 0 4px 20px rgba(0, 0, 0, 0.3);
    }

    .screenshot-footer {
      margin-top: 20px;
      text-align: center;
      color: #888;
      font-size: 12px;
    }
  </style>
</head>
<body class="dark-theme">
  <div class="screenshot-header">
    <h1>${platform.name} Platform Frame</h1>
    <p>Theme: Dark | Category: ${platform.category} | Platform: ${platform.id}</p>
  </div>

  <div class="platform-frame-container" id="frame-container">
    <!-- Frame will be rendered here -->
  </div>

  <div class="screenshot-footer">
    Generated by Vista Dark Theme Screenshot Capture (Bead bf-b6pnm)
  </div>

  <script src="../../src/public/platform-frames.js"></script>
  <script src="../../src/public/app.js"></script>
  <script>
    // Sample content matching bead requirements
    const sampleContent = {
      meta: {
        og: {
          title: 'Comprehensive Platform Frame Testing',
          description: 'This is a detailed description used to test how different platform frames handle content rendering with dark theme.',
          image: 'https://picsum.photos/800/600',
          site_name: 'VistaTest'
        },
        title: 'Comprehensive Platform Frame Testing',
        description: 'This is a detailed description used to test how different platform frames handle content rendering with dark theme.',
        themeColor: '#5865f2'
      },
      imageProbe: {
        dominantColor: '#667eea'
      },
      baseUrl: 'https://example.com/test-article'
    };

    // Render the platform frame using renderPlatformWithContext
    const platformId = '${platform.id}';
    const theme = '${THEME}';
    const container = document.getElementById('frame-container');

    try {
      const html = renderPlatformWithContext(
        platformId,
        sampleContent.meta,
        sampleContent.imageProbe,
        sampleContent.baseUrl,
        theme,
        sampleContent.imageProbe.dominantColor
      );
      container.innerHTML = html;
      console.log('✅ Frame rendered successfully for ${platform.id} in dark theme');
    } catch (error) {
      container.innerHTML = '<div style="padding: 20px; color: red;">Error rendering frame: ' + error.message + '</div>';
      console.error('❌ Frame rendering error for ${platform.id}:', error);
    }
  </script>
</body>
</html>`;
}

// Generate HTML files for all platforms
PLATFORMS.forEach(platform => {
  const html = createPlatformHTML(platform);
  const filename = `${platform.id}-dark.html`;
  const filepath = path.join(OUTPUT_DIR, filename);

  fs.writeFileSync(filepath, html);
  console.log(`✅ Generated: ${filename}`);
});

console.log(`\n📁 Generated ${PLATFORMS.length} dark theme HTML files in: ${OUTPUT_DIR}`);
console.log('\n🎯 Next steps:');
console.log('1. Open each HTML file in a browser');
console.log('2. Take a screenshot of the platform frame');
console.log('3. Save as platform-name-dark.png');
console.log('4. Run verification script');

process.exit(0);
